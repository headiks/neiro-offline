"""Подстановка наставника/руководителя в текст сообщения: в поле бывает должность, а не ФИО
(«Главный администратор») — роль ставим в нужном падеже, значение — в скобках. Без БД."""
import test_stubs
test_stubs.install(psycopg=True, stub_modules=())

import employees  # noqa: E402

EMP = {"full_name": "Смирнова Марина Олеговна", "mentor": "Главный администратор", "manager": ""}


def sub(text, emp=EMP):
    return employees.substitute(text, emp)


def test_role_case_and_value_in_brackets():
    assert sub("Если что-то неясно — напишите [ФИО наставника].") == \
        "Если что-то неясно — напишите наставнику (Главный администратор)."
    assert sub("Сомневаетесь — начните с наставника [ФИО наставника].") == \
        "Сомневаетесь — начните с наставника (Главный администратор)."
    assert sub("Обратитесь к наставнику ([ФИО наставника]).") == "Обратитесь к наставнику (Главный администратор)."
    assert sub("Позовите [ФИО наставника] или коллегу.") == "Позовите наставника (Главный администратор) или коллегу."
    assert sub("Встреча с [ФИО наставника].") == "Встреча с наставником (Главный администратор)."
    assert sub("[Имя], добрый день!") == "Марина, добрый день!"


def test_empty_field_leaves_role_not_placeholder():
    assert sub("Сообщите [ФИО руководителя].") == "Сообщите руководителю."
    assert sub("Вопросы — к руководителю ([ФИО руководителя]).") == "Вопросы — к руководителю."
