"""Страховка поверх промпта ответа: вырезаются намёки на незаполненный исходный текст."""
import sys
import types

sys.modules.setdefault("indexing", types.SimpleNamespace())
import rag  # noqa: E402


def test_strips_not_filled_hints():
    s = rag._strip_doc_refs
    assert s("Имя наставника мне неизвестно — эти поля не заполнены. Уточните у мастера.") == \
        "Имя наставника мне неизвестно. Уточните у мастера."
    assert s("Премия составляет до 20% (точный размер в процентах не указан — уточните в бухгалтерии). Она зависит от плана.") == \
        "Премия составляет до 20%. Она зависит от плана."
    # обычный текст не трогаем
    assert s("Пропуск выдают на проходной №1, данные паспорта сверяют на месте.") == \
        "Пропуск выдают на проходной №1, данные паспорта сверяют на месте."
